#!/usr/bin/env python3
"""Generate fixed-point MP2 butterflies/tables and prove intermediate bounds.

The source is the original float butterfly network, not measured audio peaks.
Exact affine coefficients plus a propagated half-LSB rounding-error bound cover
every intermediate and every subband input in [-65536,65536].
"""
import ast
from fractions import Fraction as F
import math
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / "pl_mpeg.h").read_text()
body = source.split("void plm_audio_idct36(int s[32][3], int ss, float *d, int dp) {", 1)[1].split("\n}", 1)[0]
body = body[body.index("t01 ="):]
body = re.sub(r"(\d+\.\d+)f", r"\1", body.replace("(float)", ""))
tree = ast.parse(body.replace("\t", "").strip())

class Affine:
    def __init__(self, coefficients, error=F(0)):
        self.c, self.error = coefficients, error

def evaluate(node, state, bits, fixed, bounds):
    if isinstance(node, ast.Name): return state[node.id]
    if isinstance(node, ast.Constant): return F(str(node.value))
    if isinstance(node, ast.Subscript):
        i = node.value.slice.value
        return Affine([F((1 << bits) if k == i else 0) for k in range(32)])
    if isinstance(node, ast.UnaryOp):
        a = evaluate(node.operand, state, bits, fixed, bounds)
        result = Affine([-x for x in a.c], a.error)
    else:
        a = evaluate(node.left, state, bits, fixed, bounds)
        b = evaluate(node.right, state, bits, fixed, bounds)
        if isinstance(node.op, ast.Mult):
            if fixed: b = F(math.floor(b * (1 << 27) + F(1, 2)), 1 << 27)
            result = Affine([x * b for x in a.c], abs(b) * a.error + (F(1, 2) if fixed else 0))
        else:
            sign = 1 if isinstance(node.op, ast.Add) else -1
            result = Affine([x + sign*y for x,y in zip(a.c,b.c)], a.error+b.error)
    bounds.append(sum(abs(x) for x in result.c)*65536 + result.error)
    return result

def analyse(bits, fixed=True):
    state, output, bounds = {}, {}, []
    for statement in tree.body:
        if isinstance(statement, ast.AugAssign):
            expression = ast.BinOp(statement.target, statement.op, statement.value)
            targets = [statement.target]
        else: expression, targets = statement.value, statement.targets
        value = evaluate(expression, state, bits, fixed, bounds)
        for target in targets:
            if isinstance(target, ast.Name): state[target.id] = value
            else: output[target.slice.right.value] = value
    return max(bounds), output

bits = max(b for b in range(16) if analyse(b)[0] < (1 << 31)-1)
bound, _ = analyse(bits)
assert bits == 9, "Revisit synthesis scaling if the butterfly network changes"

def emit(node):
    if isinstance(node, ast.Name): return node.id
    if isinstance(node, ast.Constant): return str(int(node.value))
    if isinstance(node, ast.Subscript):
        if isinstance(node.value, ast.Name): return ast.unparse(node)
        return f"(s[{node.value.slice.value}][ss] * PLM_AUDIO_HISTORY_SCALE)"
    if isinstance(node, ast.UnaryOp): return f"(-{emit(node.operand)})"
    if isinstance(node.op, ast.Mult):
        coefficient = math.floor(F(str(node.right.value))*(1 << 27)+F(1,2))
        return f"plm_audio_mul_s32({emit(node.left)}, INT32_C({coefficient}))"
    return f"({emit(node.left)} {'+' if isinstance(node.op, ast.Add) else '-'} {emit(node.right)})"

network = ["/* Generated by tools/audio_s32_generate.py; do not edit. */",
           "#ifndef PL_MPEG_AUDIO_S32_TRANSFORM_H", "#define PL_MPEG_AUDIO_S32_TRANSFORM_H",
           f"/* All intermediates <= {math.ceil(bound)} for |subband| <= 65536.",
           f" * {bits+1} fractional bits exceed INT32_MAX; this is the largest safe scale. */",
           "static void plm_audio_idct36_s32(int s[32][3], int ss, int32_t *d, int dp) {",
           "    int32_t " + ", ".join(f"t{i:02}" for i in range(1,34)) + ";"]
for statement in tree.body:
    if isinstance(statement, ast.AugAssign):
        network.append(f"    {emit(statement.target)} += {emit(statement.value)};")
    else:
        network.append("    " + " = ".join([ast.unparse(t) for t in statement.targets]+[emit(statement.value)])+";")
network += ["}", "#endif"]

window = source.split("static const float PLM_AUDIO_SYNTHESIS_WINDOW[] = {",1)[1].split("};",1)[0]
coefficients = [F(x) for x in re.findall(r"-?\d+\.\d+", window)]
assert len(coefficients) == 512
# 1090519040 = 65 * 2^24. With Q9 history and Q30 per-product rounding,
# -window * 2^21 / 65 followed by a seven-bit left shift produces Q1.31 PCM.
table = [math.floor(-x*(1 << 21)/65+F(1,2)) for x in coefficients]
tables = ["/* Generated by tools/audio_s32_generate.py; do not edit. */",
          "#ifndef PL_MPEG_AUDIO_S32_TABLES_H", "#define PL_MPEG_AUDIO_S32_TABLES_H",
          "#define PLM_AUDIO_HISTORY_BITS 9", "#define PLM_AUDIO_HISTORY_SCALE 512",
          "#define PLM_AUDIO_WINDOW_LEFT 7", "#ifndef __ASSEMBLER__",
          "static const int32_t plm_audio_window_s32_table[512] = {"]
for i in range(0,512,8): tables.append("    " + ", ".join(map(str,table[i:i+8]))+",")
tables += ["};", "#endif", "#endif"]
for name, lines in [("pl_mpeg_audio_s32_transform.h",network), ("pl_mpeg_audio_s32_tables.h",tables)]:
    text = "\n".join(lines)+"\n"
    path = ROOT/name
    if "--check" in sys.argv: assert path.read_text() == text, name
    else: path.write_text(text)
print(f"PASS: Q{bits} history, exact affine/rounding bound {float(bound):.3f}; next scale overflows")
